-- Localidades corregidas del organismo -- localidades_corregidas
--
-- Una fila por persona: el DNI y la localidad de su domicilio tal como la tiene
-- el organismo en su planilla. La usa `manage.py corregir_datos_siis` para
-- reemplazar la localidad de los casos cuyo texto no cruza el catalogo de SIIS.
--
-- La correccion se guarda como correccion del caso (datos_siis): la respuesta
-- que dio el ciudadano no se toca.
--
-- El DNI va como texto: con INT se pierden los ceros a la izquierda. El cruce
-- normaliza igual (con y sin ceros), asi que da lo mismo como este cargado.
--
-- Se ejecuta contra la base, no desde el pod (la imagen no trae cliente):
--   mariadb -h <host> -u <usuario> -p <base> < scripts/Localidades.sql

